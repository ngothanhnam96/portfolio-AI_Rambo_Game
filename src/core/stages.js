/**
 * Stage data. Each stage is a list of 12-row ASCII chunks (legend in level.js) followed by the
 * boss arena. tests/stages.test.js searches the real player physics to prove the arena is
 * reachable from the start and from every checkpoint.
 *
 * Reach rules used when authoring: a jump rises 3 tiles at most and clears gaps of 3 tiles
 * at the same height. Ledges (=) sit 3 tiles above the ground, or 3 tiles above another ledge.
 */

import { arenaChunk, joinChunks, Level } from "./level.js";

/** Template literal → array of rows (blank lines and indentation stripped). */
function chunk(text) {
  return text.split("\n").map((line) => line.trim()).filter((line) => line.length > 0);
}

